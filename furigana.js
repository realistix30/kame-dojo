  const PAIRS = MAP.filter(e => e.length === 2 && e[1]);

  // ── Longest-match tokeniser ───────────────────────────────────────
  function apply(text) {
    let result = '';
    let i = 0;
    while (i < text.length) {
      let matched = false;
      for (const [kanji, reading] of PAIRS) {
        if (text.startsWith(kanji, i)) {
          result += `<ruby>${kanji}<rt>${reading}</rt></ruby>`;
          i += kanji.length;
          matched = true;
          break;
        }
      }
      if (!matched) {
        result += text[i];
        i++;
      }
    }
    return result;
  }

  // Public: annotate if level is n5 or n4 (all categories)
  function annotate(text, level) {
    if (level === 'n5' || level === 'n4') return apply(text);
    return text;
  }

